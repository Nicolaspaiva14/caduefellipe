-- 1. Criar a tabela comentarios (caso ainda não exista)
CREATE TABLE IF NOT EXISTS public.comentarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cidade TEXT NOT NULL,
    estrelas TEXT DEFAULT '5',
    texto TEXT NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- 2. Habilitar Row Level Security (RLS)
ALTER TABLE public.comentarios ENABLE ROW LEVEL SECURITY;

-- 3. Políticas de acesso:
-- Qualquer visitante pode ler os comentários
DROP POLICY IF EXISTS "Permitir leitura publica de comentarios" ON public.comentarios;
CREATE POLICY "Permitir leitura publica de comentarios"
    ON public.comentarios FOR SELECT
    TO public
    USING (true);

-- Qualquer visitante pode enviar um novo comentário
DROP POLICY IF EXISTS "Permitir insercao publica de comentarios" ON public.comentarios;
CREATE POLICY "Permitir insercao publica de comentarios"
    ON public.comentarios FOR INSERT
    TO public
    WITH CHECK (true);

-- Permitir exclusão de comentários (pelo painel de administração)
DROP POLICY IF EXISTS "Permitir exclusao de comentarios" ON public.comentarios;
CREATE POLICY "Permitir exclusao de comentarios"
    ON public.comentarios FOR DELETE
    TO public
    USING (true);

