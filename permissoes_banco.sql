-- 1. TABELA DE MENSAGENS DE CONTATO (mensagens_contato)
ALTER TABLE IF EXISTS public.mensagens_contato ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura de mensagens" ON public.mensagens_contato;
CREATE POLICY "Permitir leitura de mensagens"
    ON public.mensagens_contato FOR SELECT
    TO public
    USING (true);

DROP POLICY IF EXISTS "Permitir insercao de mensagens" ON public.mensagens_contato;
CREATE POLICY "Permitir insercao de mensagens"
    ON public.mensagens_contato FOR INSERT
    TO public
    WITH CHECK (true);

-- Permite excluir mensagens pelo painel administrativo
DROP POLICY IF EXISTS "Permitir exclusao de mensagens" ON public.mensagens_contato;
CREATE POLICY "Permitir exclusao de mensagens"
    ON public.mensagens_contato FOR DELETE
    TO public
    USING (true);


-- 2. TABELA DE FOTOS DA GALERIA (fotos)
CREATE TABLE IF NOT EXISTS public.fotos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    descricao TEXT NOT NULL,
    criado_em TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

ALTER TABLE public.fotos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Permitir leitura de fotos" ON public.fotos;
CREATE POLICY "Permitir leitura de fotos"
    ON public.fotos FOR SELECT
    TO public
    USING (true);

DROP POLICY IF EXISTS "Permitir insercao de fotos" ON public.fotos;
CREATE POLICY "Permitir insercao de fotos"
    ON public.fotos FOR INSERT
    TO public
    WITH CHECK (true);

-- Permite excluir fotos pelo painel administrativo (remove da galeria principal na hora)
DROP POLICY IF EXISTS "Permitir exclusao de fotos" ON public.fotos;
CREATE POLICY "Permitir exclusao de fotos"
    ON public.fotos FOR DELETE
    TO public
    USING (true);


