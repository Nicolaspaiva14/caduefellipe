-- 4. BUCKET DE ARMAZENAMENTO PARA FOTOS (Storage)
-- Garante que o bucket 'fotos' seja acessível publicamente caso use upload de arquivo
INSERT INTO storage.buckets (id, name, public)
VALUES ('fotos', 'fotos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Fotos Public Storage SELECT" ON storage.objects;
CREATE POLICY "Fotos Public Storage SELECT" ON storage.objects FOR SELECT TO public USING (bucket_id = 'fotos');

DROP POLICY IF EXISTS "Fotos Public Storage INSERT" ON storage.objects;
CREATE POLICY "Fotos Public Storage INSERT" ON storage.objects FOR INSERT TO public WITH CHECK (bucket_id = 'fotos');

DROP POLICY IF EXISTS "Fotos Public Storage DELETE" ON storage.objects;
CREATE POLICY "Fotos Public Storage DELETE" ON storage.objects FOR DELETE TO public USING (bucket_id = 'fotos');
